#!/usr/bin/env python3
"""
dxcc_monitor.py — Real-time DXCC monitor via Telnet DX Cluster
Compares cluster spots against your ADIF log and sends Telegram alerts for new entities.

Usage:
    python3 dxcc_monitor.py --callsign YOURCALL --telegram-token TOKEN --telegram-chat-id CHAT_ID
    python3 dxcc_monitor.py --callsign YOURCALL --modes SSB,FT8 --years 2026
"""

